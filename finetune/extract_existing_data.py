def create_legal_qa_dataset():
    """创建法律问答训练数据集"""
    print("Creating legal QA training dataset...")
    
    # 系统提示词模板
    system_prompt = "你是\"律法通\"法律咨询助手，专注于中国法律领域。请基于提供的法律条文和知识回答用户问题。回答必须遵循\"事实-法律适用-结论\"推理链结构。"
    
    dataset = []
    
    # 从FAQ数据生成训练样本
    for faq in FAQ_DATA:
        instruction = system_prompt
        input_text = faq["question"]
        output_text = f"【法律领域】{faq['category']}\n\n{faq['answer']}"
        
        dataset.append({
            "instruction": instruction,
            "input": input_text,
            "output": output_text
        })
    
    print(f"Generated {len(dataset)} samples from FAQ data")
    return dataset


def create_law_qa_dataset():
    """创建法条问答训练数据集"""
    print("Creating law article QA training dataset...")
    
    system_prompt = "你是\"律法通\"法条查询助手，专注于精准检索和解释中国法律条文。"
    
    dataset = []
    
    # 为每个法律条文创建问答对
    for law in LAW_DATA:
        for article in law["articles"]:
            # 提取条款编号
            parts = article.split(" ")
            if len(parts) >= 2:
                article_num = parts[0]
                article_content = " ".join(parts[1:])
                
                # 创建问答对
                instruction = system_prompt
                input_text = f"{law['law_name']}{article_num}的内容是什么？"
                output_text = f"根据{law['law_name']}：\n\n**{article_num}** {article_content}"
                
                dataset.append({
                    "instruction": instruction,
                    "input": input_text,
                    "output": output_text
                })
    
    print(f"Generated {len(dataset)} samples from law articles")
    return dataset


def save_dataset(dataset, output_file):
    """保存数据集"""
    output_path = Path(output_file)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(dataset, f, ensure_ascii=False, indent=2)
    
    print(f"Dataset saved to {output_path} ({len(dataset)} samples)")


def main():
    """主函数"""
    import argparse
    
    parser = argparse.ArgumentParser(description='Extract training data from existing project data')
    parser.add_argument('--output', type=str, default='data/LawGPT-data-full.json',
                       help='Output file path')
    parser.add_argument('--type', choices=['faq', 'law', 'all'], default='all',
                       help='Type of data to extract')
    
    args = parser.parse_args()
    
    print("=" * 60)
    print("Extracting Training Data from Project")
    print("=" * 60)
    
    dataset = []
    
    if args.type in ['faq', 'all']:
        faq_data = create_legal_qa_dataset()
        dataset.extend(faq_data)
    
    if args.type in ['law', 'all']:
        law_data = create_law_qa_dataset()
        dataset.extend(law_data)
    
    if not dataset:
        print("No data to save")
        return
    
    save_dataset(dataset, args.output)
    
    print("\n" + "=" * 60)
    print("Extraction Complete!")
    print(f"Total samples: {len(dataset)}")
    print("=" * 60)


if __name__ == "__main__":
    main()
