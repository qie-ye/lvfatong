def format_sentence(meta):
    """格式化判决结果"""
    imprisonment = meta.get('term_of_imprisonment', {})
    
    if imprisonment.get('death_penalty'):
        return "判处死刑"
    elif imprisonment.get('life_imprisonment'):
        return "判处无期徒刑"
    else:
        years = imprisonment.get('imprisonment', 0)
        if years == 0:
            return "判处拘役或管制"
        elif years <= 3:
            return f"判处有期徒刑{years}年"
        elif years <= 10:
            return f"判处有期徒刑{years}年"
        else:
            return f"判处有期徒刑{years}年"


def convert_to_alpaca(data, num_samples=None):
    """将CAIL2018数据转换为Alpaca格式"""
    alpaca_data = []
    
    # 随机采样
    if num_samples and num_samples < len(data):
        import random
        random.seed(42)
        data = random.sample(data, num_samples)
    
    for item in data:
        fact = item.get('fact', '')
        meta = item.get('meta', {})
        
        # 获取罪名
        accusations = meta.get('accusation', [])
        if not accusations:
            continue
        
        crime_name = accusations[0] if accusations else "犯罪"
        
        # 获取相关法律条文
        relevant_articles = meta.get('relevant_articles', [])
        articles_text = ""
        for article_num in relevant_articles:
            if article_num in ARTICLE_MAP:
                articles_text += ARTICLE_MAP[article_num] + "\n"
        
        if not articles_text:
            articles_text = f"【刑法】相关条款（第{relevant_articles[0]}条）" if relevant_articles else ""
        
        # 构建问答对
        instruction = "你是'律法通'法律咨询助手，专注于中国刑法领域。请基于提供的案件事实和法律条文回答用户问题。"
        
        question = get_question_for_crime(crime_name)
        
        # 构建回答
        sentence = format_sentence(meta)
        
        output = f"""【案件事实】
{fact}

【法律适用】
{articles_text}

【判决结果】
{sentence}

【法律分析】
根据上述法律规定，本案中被告人的行为构成{crime_name}。
{sentence}是基于案件事实和法律规定作出的判决。"""
        
        alpaca_item = {
            "instruction": instruction,
            "input": question,
            "output": output
        }
        alpaca_data.append(alpaca_item)
    
    return alpaca_data


